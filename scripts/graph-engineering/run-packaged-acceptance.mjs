import { execFile, spawn } from "node:child_process";
import { mkdir, readFile, readdir, rename, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import { promisify } from "node:util";
import { resolveDistDirName } from "./release-manifest.mjs";
import { verifyPackageHashes } from "./verify-package-hashes.mjs";

/**
 * 对一个已构建的包运行完整打包套件，并生成「验证补充」文件：
 * 运行前后各核对一次包哈希；记录 packaged-smoke 进程的真实退出码与每个用例的结果；
 * 分开记录二进制的构建来源提交和测试脚本（harness）的来源提交；保留此前所有尝试的摘要。
 * 原始 RELEASE_MANIFEST.json 不改动——补充文件按哈希指向它，PASS 不会被写进清单。
 * 用法：run-packaged-acceptance.mjs <版本> [--dist-dir dist-graph-b1]
 */
const root = path.resolve(import.meta.dirname, "../..");
const args = process.argv.slice(2);
const version = args[0];
const distName = resolveDistDirName(
  args.includes("--dist-dir") ? args[args.indexOf("--dist-dir") + 1] : undefined,
);
if (!version) throw new Error("usage: run-packaged-acceptance.mjs <version> [--dist-dir <name>]");
const dist = path.join(root, "packages/desktop", distName);
const git = async (...gitArgs) =>
  (await promisify(execFile)("git", gitArgs, { cwd: root })).stdout.trim();
const exists = (file) =>
  stat(file).then(
    () => true,
    () => false,
  );

// 此前的补充文件和哈希核对结果也进入历史，不覆盖。
const stamp = new Date().toISOString().replace(/[:.]/g, "-");
const history = path.join(dist, "packaged-smoke-history", `supplement-${stamp}`);
for (const name of [
  "PACKAGED_VALIDATION_SUPPLEMENT.json",
  "packaged-hash-check.before.json",
  "packaged-hash-check.after.json",
]) {
  if (await exists(path.join(dist, name))) {
    await mkdir(history, { recursive: true });
    await rename(path.join(dist, name), path.join(history, name));
  }
}

const before = await verifyPackageHashes(dist);
await writeFile(
  path.join(dist, "packaged-hash-check.before.json"),
  `${JSON.stringify(before, null, 2)}\n`,
);
if (!before.ok)
  throw new Error("Package differs from its manifest before testing; refusing to test it.");

// 完整套件：不设置过滤器；keep-going 让每个用例都被如实记录，最终仍按任何失败返回非零。
const environment = {
  ...process.env,
  ZCODE_GRAPH_DIST_DIR: distName,
  ZCODE_GRAPH_SMOKE_KEEP_GOING: "1",
};
delete environment.ZCODE_GRAPH_SMOKE_CASES;
const smokeExit = await new Promise((resolve) => {
  const child = spawn(
    process.execPath,
    [path.join(import.meta.dirname, "packaged-smoke.mjs"), version],
    {
      cwd: root,
      env: environment,
      stdio: "inherit",
      windowsHide: true,
    },
  );
  child.on("close", (code) => resolve(code));
  child.on("error", () => resolve(null));
});

const after = await verifyPackageHashes(dist);
await writeFile(
  path.join(dist, "packaged-hash-check.after.json"),
  `${JSON.stringify(after, null, 2)}\n`,
);
const smoke = await readFile(path.join(dist, "packaged-smoke.json"), "utf8").then(
  JSON.parse,
  () => undefined,
);
const manifestSource = JSON.parse(
  await readFile(path.join(dist, "RELEASE_MANIFEST.json"), "utf8"),
).source;
const previous = [];
const historyRoot = path.join(dist, "packaged-smoke-history");
for (const entry of (await exists(historyRoot)) ? await readdir(historyRoot) : []) {
  const file = path.join(historyRoot, entry, "packaged-smoke.json");
  if (!(await exists(file))) continue;
  const old = JSON.parse(await readFile(file, "utf8"));
  previous.push({
    attempt: entry,
    scope: old.scope ?? "full (written before scope labels existed)",
    harnessCommit:
      old.harness?.commit ?? "not recorded (written before harness provenance existed)",
    passed: old.results.filter((r) => r.status === "PASS" && r.exitCode === 0).map((r) => r.name),
    failed: old.results
      .filter((r) => !(r.status === "PASS" && r.exitCode === 0))
      .map((r) => r.name),
  });
}
const supplement = {
  schema: "zcode-graph-packaged-validation-supplement/1",
  note: "Generated by run-packaged-acceptance.mjs. The original RELEASE_MANIFEST.json is unchanged; this file points at it by hash.",
  appliesTo: {
    version,
    installer: after.installer,
    releaseManifest: { file: "RELEASE_MANIFEST.json", sha256: after.manifestSha256 },
  },
  buildSource: { commit: manifestSource.commit, dirtyAtBuildStart: manifestSource.dirty },
  harnessSource: {
    recordedByPackagedSmoke: smoke?.harness,
    orchestratorCommit: await git("rev-parse", "HEAD"),
    orchestratorDirty: (await git("status", "--porcelain=v1", "--untracked-files=all")).length > 0,
  },
  packageHashChecks: {
    before: { file: "packaged-hash-check.before.json", ok: before.ok, checkedAt: before.checkedAt },
    after: { file: "packaged-hash-check.after.json", ok: after.ok, checkedAt: after.checkedAt },
    unchangedBetweenChecks:
      JSON.stringify(before.observed) === JSON.stringify(after.observed) &&
      before.installer.sha256 === after.installer.sha256,
  },
  packagedSmoke: smoke && {
    processExitCode: smokeExit,
    scope: smoke.scope,
    partial: smoke.partial,
    aborted: smoke.aborted,
    summary: smoke.summary,
    matchesReleaseManifest: smoke.matchesReleaseManifest,
    detachedCopyHashes: smoke.packageHashes,
    cases: smoke.results.map((r) => ({
      name: r.name,
      status: r.status,
      exitCode: r.exitCode,
      assertions: r.assertions?.length ?? 0,
      packagedIdentity: r.packagedIdentity && {
        name: r.packagedIdentity.name,
        version: r.packagedIdentity.version,
        isPackaged: r.packagedIdentity.isPackaged,
      },
      testedBuild: r.testedBuild,
      finalRunStatus: r.finalRunStatus,
      telemetryCanary: r.telemetryCanary,
      failure: r.error
        ? String(r.error)
            .split("\n")[0]
            .replace(/[A-Za-z]:[\\/][^\s"')]+/g, "<path>")
            .slice(0, 240)
        : undefined,
    })),
  },
  previousAttempts: previous,
  satisfiesFullReleaseGate:
    smokeExit === 0 && smoke?.summary?.satisfiesFullReleaseGate === true && before.ok && after.ok,
};
await writeFile(
  path.join(dist, "PACKAGED_VALIDATION_SUPPLEMENT.json"),
  `${JSON.stringify(supplement, null, 2)}\n`,
);
process.stdout.write(
  `Packaged validation supplement written; smoke exit ${smokeExit}; full gate ${supplement.satisfiesFullReleaseGate}\n`,
);
process.exitCode = supplement.satisfiesFullReleaseGate ? 0 : 1;
